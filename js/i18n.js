/* ============================================================
   I18N Object — translation engine
   ============================================================ */
const I18N = {
  currentLang: 'en',

  /**
   * Translate a key. Returns the string for currentLang.
   * Optionally interpolates {var} placeholders.
   * Falls back to EN if TE key is missing, then to the key itself.
   */
  t(key, vars) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS['en'];
    let str = dict[key] || TRANSLATIONS['en'][key] || key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      });
    }
    return str;
  },

  /**
   * Switch language, persist to localStorage, apply to DOM.
   */
  setLanguage(lang) {
    if (!['en', 'te'].includes(lang)) return;
    this.currentLang = lang;
    localStorage.setItem('golis_lang', lang);
    document.documentElement.setAttribute('lang', lang);
    this.applyTranslations();
    // Update lang switcher buttons
    document.querySelectorAll('.lang-switcher__btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });
  },

  /**
   * Read persisted language from localStorage, default 'en'.
   */
  getLanguage() {
    return localStorage.getItem('golis_lang') || 'en';
  },

  /**
   * Apply all translations to DOM elements with data-i18n attributes.
   * data-i18n="key"           → sets textContent
   * data-i18n-placeholder="key" → sets placeholder
   * data-i18n-title="key"       → sets title attribute
   * data-i18n-html="key"        → sets innerHTML (use sparingly)
   */
  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      el.textContent = this.t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.dataset.i18nTitle);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = this.t(el.dataset.i18nHtml);
    });
  },

  /**
   * Convenience: t() bound so it can be destructured or passed around.
   */
  bind() {
    return this.t.bind(this);
  }
};

// Export shorthand
const t = (key, vars) => I18N.t(key, vars);
